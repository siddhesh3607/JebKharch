import fs from 'node:fs';
import {Wallet,JsonRpcProvider,formatEther} from 'ethers';
const path='.env';
if(fs.existsSync(path))throw Error('Existing .env found; refusing to overwrite keys');
const owner=Wallet.createRandom(),session=Wallet.createRandom();
const vendors=[Wallet.createRandom().address,Wallet.createRandom().address];
fs.writeFileSync(path,`NETWORK=fuji\nPORT=3000\nFUJI_RPC_URL=https://api.avax-test.network/ext/bc/C/rpc\nDEPLOYER_PRIVATE_KEY=${owner.privateKey}\nSESSION_PRIVATE_KEY=${session.privateKey}\nVENDOR_A=${vendors[0]}\nVENDOR_B=${vendors[1]}\nANTHROPIC_API_KEY=\nCLAUDE_MODEL=\n`,{flag:'wx',mode:0o600});
const provider=new JsonRpcProvider('https://api.avax-test.network/ext/bc/C/rpc');
const network=await provider.getNetwork();if(network.chainId!==43113n)throw Error('Wrong chain');
const info={network:'Avalanche Fuji',chainId:43113,owner:owner.address,session:session.address,vendors,ownerAVAX:formatEther(await provider.getBalance(owner.address)),sessionAVAX:formatEther(await provider.getBalance(session.address))};
fs.mkdirSync('data',{recursive:true});fs.writeFileSync('data/funding.json',JSON.stringify(info,null,2));console.log(JSON.stringify(info,null,2));
